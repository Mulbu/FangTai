_UNIT_GRAMS = {
    "个": 60, "根": 80, "片": 10, "瓣": 5, "只": 100, "条": 100, "颗": 10,
    "张": 10, "勺": 10, "大勺": 15, "小勺": 5, "包": 30, "串": 60, "段": 30,
    "块": 50, "把": 30, "碗": 200, "杯": 200, "滴": 0.5, "份": 100,
    "盒": 100, "罐": 200, "袋": 30,
}

_EGG_UNIT = {"鸡蛋": 50, "鹌鹑蛋": 10, "皮蛋": 60, "咸蛋": 60}


@dataclass
class Nutrition:
    kcal: float = 0.0
    protein: float = 0.0
    fat: float = 0.0
    carbs: float = 0.0
    purine_mg: float = 0.0

    def add(self, other: "Nutrition"):
        self.kcal += other.kcal
        self.protein += other.protein
        self.fat += other.fat
        self.carbs += other.carbs
        self.purine_mg += other.purine_mg

    def scaled(self, factor: float) -> "Nutrition":
        return Nutrition(
            kcal=self.kcal * factor, protein=self.protein * factor,
            fat=self.fat * factor, carbs=self.carbs * factor,
            purine_mg=self.purine_mg * factor,
        )

    def to_dict(self) -> dict:
        return {
            "kcal": round(self.kcal), "protein_g": round(self.protein, 1),
            "fat_g": round(self.fat, 1), "carbs_g": round(self.carbs, 1),
        }

    def purine_level(self) -> str:
        if self.purine_mg < 100:
            return "低嘌呤"
        if self.purine_mg < 300:
            return "中嘌呤"
        return "高嘌呤"


def _lookup(name: str) -> tuple[float, float, float, float, float] | None:
    n = name.strip()
    if not n:
        return None
    if n in NUTRITION_TABLE:
        return NUTRITION_TABLE[n]
    for pat, key in _NAME_MAP:
        if n == pat:
            return NUTRITION_TABLE.get(key)
    # 包含式匹配：名称包含键（如"新鲜小龙虾"）或键包含名称（如"熟牛蹄筋"→最长子串）
    best = None
    best_len = 0
    for key in NUTRITION_TABLE:
        if (key in n or n in key) and len(key) > best_len and len(key) >= 2:
            best, best_len = NUTRITION_TABLE[key], len(key)
    if best:
        return best
    for pat, key in _NAME_MAP:
        if pat in n and len(pat) >= 2:
            return NUTRITION_TABLE.get(key)
    return None


def estimate_grams(ing: Ingredient) -> float:
    """估算食材克重：显式克数 > 计数单位换算 > 适量默认。"""
    if ing.grams:
        return ing.grams
    if ing.count:
        if ing.name in _EGG_UNIT:
            return ing.count * _EGG_UNIT[ing.name]
        return ing.count * _UNIT_GRAMS.get(ing.unit, 50)
    # 适量：调味料按 5g，其他按 50g
    tiny = ("盐", "糖", "粉", "酱", "油", "醋", "酒", "椒", "姜", "葱", "蒜", "茶", "香料")
    return 5.0 if any(t in ing.name for t in tiny) else 50.0


def recipe_nutrition(rec: Recipe, servings: float = 2.0) -> Nutrition:
    """整道菜营养（默认2人份）；忽略水/调料类微量项。"""
    total = Nutrition()
    for ing in rec.ingredients:
        grams = estimate_grams(ing)
        row = _lookup(ing.name)
        if row is None:
            # 未收录食材按混合均值 120kcal/100g 估
            factor = grams / 100.0
            total.kcal += 120 * factor
            total.protein += 3 * factor
            total.fat += 5 * factor
            total.carbs += 15 * factor
            continue
        kcal, prot, fat, carb, purine = row
        factor = grams / 100.0
        total.kcal += kcal * factor
        total.protein += prot * factor
        total.fat += fat * factor
        total.carbs += carb * factor
        total.purine_mg += purine * factor
    return total.scaled(1.0 / max(servings, 0.1))


def adaptive_servings(rec, people: int) -> float:
    """按菜品体量自适应份额：大锅汤/整鸡等按更多份数折算，避免营养高估。"""
    total_grams = sum(estimate_grams(i) for i in rec.ingredients)
    return max(float(people), round(total_grams / 550.0))


# 每人每餐参考摄入目标（轻体力成人单餐约全日40%）
MEAL_TARGET = {
    "低": Nutrition(kcal=720, protein=28, fat=24, carbs=100),
    "中": Nutrition(kcal=880, protein=34, fat=28, carbs=125),
    "高": Nutrition(kcal=1040, protein=42, fat=32, carbs=150),
}


def balance_report(n: Nutrition, labor: str = "中") -> dict:
    """营养均衡度报告：相对目标的偏差比例。"""
    target = MEAL_TARGET.get(labor, MEAL_TARGET["中"])
    def dev(actual: float, t: float) -> float:
        return round((actual - t) / t * 100, 1) if t else 0.0
    return {
        "intake": n.to_dict(),
        "target_kcal": target.kcal,
        "deviation_pct": {
            "kcal": dev(n.kcal, target.kcal),
            "protein": dev(n.protein, target.protein),
            "fat": dev(n.fat, target.fat),
            "carbs": dev(n.carbs, target.carbs),
        },
        "purine_level": n.purine_level(),
    }
